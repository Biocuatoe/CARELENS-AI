"""Convert the greeting MP3 asset into src/greeting_mp3.h (a const byte array in flash), after checking its format.

The source of truth is the committed MP3, made once from the Piper WAV (assets/greeting_vi_xin_chao_16k.wav, kept as the
master recording; Piper's VITS synthesis samples noise, so it is not bit-reproducible) with LAME:
  python tools/make_test_mp3.py encode assets/greeting_vi_xin_chao_16k.wav assets/greeting_vi_xin_chao_16k.mp3 --kbps 48
This step is deterministic. Run it after replacing the MP3:
  python tools/embed_asset.py
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSET = ROOT / "assets" / "greeting_vi_xin_chao_16k.mp3"
HEADER = ROOT / "src" / "greeting_mp3.h"

KBPS_V2 = [0, 8, 16, 24, 32, 40, 48, 56, 64, 80, 96, 112, 128, 144, 160, 0]


def check(mp3: bytes) -> tuple[int, int, int]:
    """Header walk with the firmware's rules (src/mp3.cpp), restricted to what the greeting must be: MPEG-2 Layer III,
    16 kHz, mono, whole frames, no tags. Returns (sample rate, frames, samples per channel)."""
    pos, frames = 0, 0
    while pos < len(mp3):
        h = mp3[pos : pos + 4]
        if len(h) < 4 or h[0] != 0xFF or (h[1] & 0xE0) != 0xE0:
            raise SystemExit(f"no MP3 frame header at byte {pos}")
        version, layer, br, sr, pad, mode = (h[1] >> 3) & 3, (h[1] >> 1) & 3, h[2] >> 4, (h[2] >> 2) & 3, (h[2] >> 1) & 1, h[3] >> 6
        if (version, layer, sr, mode) != (2, 1, 2, 3) or br in (0, 15):
            raise SystemExit(f"greeting must be MPEG-2 Layer III 16 kHz mono with a fixed bitrate index (frame {frames})")
        size = 72000 * KBPS_V2[br] // 16000 + pad
        if pos + size > len(mp3):
            raise SystemExit(f"frame {frames} truncated")
        pos += size
        frames += 1
    if frames == 0:
        raise SystemExit("no frames")
    return 16000, frames, frames * 576


def main() -> int:
    mp3 = ASSET.read_bytes()
    rate, frames, samples = check(mp3)
    digest = hashlib.sha256(mp3).hexdigest()
    lines = [
        "// Generated by tools/embed_asset.py from assets/greeting_vi_xin_chao_16k.mp3. Do not edit.",
        f'// "Xin chao." MP3 MPEG-2 Layer III mono {rate} Hz, {frames} frames ({samples * 1000 // rate} ms incl. encoder delay), {len(mp3)} bytes.',
        f"// SHA-256 {digest}",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        f'#define CARELENS_GREETING_SHA256 "{digest}"',
        f"static const size_t kGreetingMp3Len = {len(mp3)};",
        "static const uint8_t kGreetingMp3[] = {",
    ]
    for i in range(0, len(mp3), 20):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in mp3[i : i + 20]) + ",")
    lines.append("};")
    HEADER.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {HEADER.relative_to(ROOT)}: {len(mp3)} bytes, {frames} frames, sha256 {digest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
